// The people the redirects send to, from redirects.json (yours, kept out of git) or else redirects.example.json:
// a list like ["< Sam", "Alex >"], where "< Sam" sits to the left of the bar and "Alex >" to the right, as someone
// facing the front display sees it. Checks that every name fits the front and the back menu, then writes
// src/generated/redirects.ts for presets.ts.
// Usage: node assets/redirects.ts   (the first step of `pnpm assets`)

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { font, textWidth } from "@vladzaharia/bar-pixel";

/**
 * Widest name on the front in the large font: 46 px, about five letters (DAMIAN is exactly 46). Every style lays itself
 * out from the name's ink width and drops decorations before they would touch it (chevrons, the walker's "!", the
 * visitor's walk). What cannot shrink sets the limit: with a 46 px name the paper plane keeps its nose 2 px off the
 * edge, the motorway sign has 3 px to spare, and the parcel van is 65 of the 72 px long (its cargo box is the name
 * plus 4 px either side).
 */
const MAX_NAME_WIDTH = 46;
/** The back menu spreads its rows over 43 px; past 7 entries they would be closer than the 5 px lettering. */
const MAX_ENTRIES = 7;

const at = (path: string) => fileURLToPath(new URL(`../${path}`, import.meta.url));
const source = ["redirects.json", "redirects.example.json"].find((f) => existsSync(at(f)))!;
const fail = (why: string): never => {
  console.error(`${source}: ${why}`);
  process.exit(1);
};

const list: unknown = JSON.parse(readFileSync(at(source), "utf8"));
if (!Array.isArray(list)) fail('expected a list like ["< Sam", "Alex >"]');
if ((list as unknown[]).length + 1 > MAX_ENTRIES) fail(`at most ${MAX_ENTRIES - 1} people fit the back menu`);

const people = (list as unknown[]).map((item) => {
  const m = typeof item === "string" ? /^\s*<\s*([^<>]+?)\s*$|^\s*([^<>]+?)\s*>\s*$/.exec(item) : null;
  if (!m) return fail(`${JSON.stringify(item)}: write "< Name" for someone on the left, "Name >" on the right`);
  const name = (m[1] ?? m[2]!).toUpperCase();
  if (!/^[A-Z0-9][A-Z0-9 .'-]*$/.test(name)) fail(`${name}: letters, digits, spaces, . ' and - only`);
  const width = textWidth(name, font("extra_large"));
  if (width > MAX_NAME_WIDTH) fail(`${name} is ${width} px wide on the front; at most ${MAX_NAME_WIDTH} fit (about five letters)`);
  // The Mac remote names entries by id ("play sam random"), and works ids out the same way (Catalog.swift).
  const id = name.toLowerCase().replace(/[^a-z0-9]/g, "");
  return { id, name, dir: m[1] !== undefined ? -1 : 1 };
});
const ids = people.map((p) => p.id);
const clash = ids.find((id, i) => id === "ticket" || ids.indexOf(id) !== i);
if (clash) fail(`two entries would both be "${clash}"`);

mkdirSync(at("src/generated"), { recursive: true });
writeFileSync(
  at("src/generated/redirects.ts"),
  [
    `// Generated by assets/redirects.ts from ${source}. Do not edit.`,
    "",
    "/** The people the redirects send to: dir 1 to the right of the bar, -1 to the left. */",
    `export const PEOPLE: { id: string; name: string; dir: 1 | -1 }[] = ${JSON.stringify(people)};`,
    "",
  ].join("\n"),
);
console.log(`redirects (${source}): ${people.map((p) => (p.dir < 0 ? `< ${p.name}` : `${p.name} >`)).join(", ") || "none"}`);
