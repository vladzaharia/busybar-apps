// Renders the app's assets into src/: the "hello" scene, the clock's calendar, the app icons, and
// src/generated/clips.ts with the timings the app sequences by. Compose scenes from the component catalog
// (packages/pixel/src/catalog.ts; see the gallery) and the motion tokens (MOTION).
// Usage: pnpm assets   (also part of `pnpm build` and `pnpm typecheck`)

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import {
  MOTION,
  buildAnim,
  calendarIcon,
  capCentre,
  dropIn,
  fadeInOut,
  font,
  hex,
  layer,
  monogramIcon,
  panel,
  sparkles,
  textWidth,
  writePng,
  type Raster,
} from "@vladzaharia/bar-pixel";

const SRC = fileURLToPath(new URL("../src/", import.meta.url));
const write = (path: string, data: Uint8Array | string) => {
  mkdirSync(dirname(join(SRC, path)), { recursive: true });
  writeFileSync(join(SRC, path), data);
};
const png = (path: string, r: Raster) => {
  mkdirSync(dirname(join(SRC, path)), { recursive: true });
  writePng(join(SRC, path), { width: r.width, height: r.height, data: r.toRGBA8() });
};

// The hello scene: a sign panel with the name dropping in and a few sparkles, fading in over the clock and away.
const NAME = "{{NAME_UPPER}}";
const SHOW = 3;
// The biggest font the name fits in, inside the panel's border.
const nameFont = (["extra_large", "bold", "small"] as const).find((f) => textWidth(NAME, font(f)) <= 66) ?? "small";
const textX = Math.round((72 - textWidth(NAME, font(nameFont))) / 2);
const hello = fadeInOut(
  layer(
    panel({ duration: SHOW }),
    dropIn({ text: NAME, font: nameFont, x: textX, y: capCentre(nameFont), duration: SHOW }),
    sparkles({ duration: SHOW, count: 6 }),
  ),
  { fadeIn: MOTION.base, fadeOut: MOTION.base },
);
const built = buildAnim({ width: 72, height: 16, fps: 60, format: "argb8888", parts: [["default", hello]] });
write("animations/hello.anim", built.data);

png("images/calendar.png", calendarIcon());
png("appmeta/icon_front_8x8.png", monogramIcon(NAME, 8, hex("#1D7AFC")));
png("appmeta/icon_back_11x11.png", monogramIcon(NAME, 11, hex("#9A9A9A"), hex("#000000")));

write(
  "generated/clips.ts",
  [
    "// Generated by assets/build.ts. Do not edit.",
    "",
    'import type { Clip } from "@vladzaharia/bar-core";',
    "",
    `export const HELLO: Clip = { path: "animations/hello.anim", fps: ${built.fps}, sections: ${JSON.stringify(built.sections)} };`,
    'export const CALENDAR = "images/calendar.png";',
    "",
  ].join("\n"),
);
console.log(`animations/hello.anim: ${built.sections.default} frames, ${(built.data.length / 1024).toFixed(0)} KB`);
