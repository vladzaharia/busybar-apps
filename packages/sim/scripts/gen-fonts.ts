// Generates src/fonts.generated.ts: the device fonts' printable-ASCII glyphs as compact bitmaps, so the simulator
// draws text exactly as the firmware does. Usage: pnpm --filter @vladzaharia/bar-sim fonts

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { font, type FontName } from "@vladzaharia/bar-pixel";

const FONTS: FontName[] = ["tiny", "small", "normal", "condensed", "bold", "large", "extra_large", "superscript"];
const out: Record<string, { ascent: number; descent: number; glyphs: (number | string)[][] }> = {};
for (const name of FONTS) {
  const f = font(name);
  const glyphs: (number | string)[][] = [];
  for (let c = 0x20; c <= 0x7e; c++) {
    const g = f.glyph(c);
    if (!g) {
      glyphs.push([0, 0, 0, 0, 0, ""]);
      continue;
    }
    // Bits packed into hex, row-major, 4 bits per digit.
    let hex = "";
    for (let i = 0; i < g.bits.length; i += 4) {
      hex += ((g.bits[i]! << 3) | ((g.bits[i + 1] ?? 0) << 2) | ((g.bits[i + 2] ?? 0) << 1) | (g.bits[i + 3] ?? 0)).toString(16);
    }
    glyphs.push([g.advance, g.x, g.y, g.width, g.height, hex]);
  }
  out[name] = { ascent: f.ascent, descent: f.descent, glyphs };
}
const file = fileURLToPath(new URL("../src/fonts.generated.ts", import.meta.url));
writeFileSync(
  file,
  `// Generated by scripts/gen-fonts.ts from the BUSY Bar firmware fonts. Do not edit.\n// Per font: ascent, descent, and for 0x20..0x7E [advance, x, y, width, height, hex bits].\n\nexport const FONTS: Record<string, { ascent: number; descent: number; glyphs: (number | string)[][] }> = ${JSON.stringify(out)};\n`,
);
console.log(`wrote ${file}`);
